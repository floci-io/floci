package io.floci.aws.services.s3;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.floci.aws.core.common.VendoredResources;

import java.io.IOException;
import java.io.InputStream;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * The bucket sub-resources botocore's S3 model defines, read once from the vendored {@code aws/rest-routes.json}:
 * each query parameter without a value that a {@code /{Bucket}} route names ({@code ?acl}, {@code ?metadataTable}),
 * and the operations it selects by HTTP method. A bucket request naming one runs that operation in AWS, never the
 * bucket's own, so {@link S3Controller} answers one it does not serve with an error, and the IAM registry checks it
 * as the operation it names.
 *
 * <p>The file is generated by {@code tools/aws/regen_rest_routes.py}. A missing or malformed resource is a build
 * defect, so loading fails with {@link IllegalStateException} rather than leaving every sub-resource to run as the
 * bucket's operation.
 */
public final class S3BucketSubresources {

    static final String RESOURCE_NAME = "aws/rest-routes.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final String BUCKET_ROUTE = "/{Bucket}?";

    private static final class Holder {
        static final S3BucketSubresources VENDORED = VendoredResources.read(RESOURCE_NAME,
                "S3 bucket sub-resource table", S3BucketSubresources::parse);
    }

    /** Each sub-resource's operations by method, in name order. */
    private final Map<String, Map<String, List<String>>> operations;
    private final List<String> names;

    private S3BucketSubresources(Map<String, Map<String, List<String>>> operations, List<String> names) {
        this.operations = operations;
        this.names = names;
    }

    /** The sub-resources of the vendored model. */
    public static S3BucketSubresources vendored() {
        return Holder.VENDORED;
    }

    /** The sub-resources' names, in order. */
    public List<String> names() {
        return names;
    }

    /** The operations the sub-resource selects for the method, in order; empty when S3 defines none for it. */
    public List<String> operations(String method, String subresource) {
        return operations.getOrDefault(subresource, Map.of()).getOrDefault(method, List.of());
    }

    static S3BucketSubresources parse(InputStream in) throws IOException {
        JsonNode document = MAPPER.readTree(in);
        JsonNode model = document == null ? null : document.path("models").path("s3").path("operations");
        if (model == null || !model.isObject() || model.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no S3 operations");
        }
        Map<String, Map<String, TreeSet<String>>> found = new TreeMap<>();
        model.properties().forEach(operation -> {
            String method = operation.getValue().path("method").asText("");
            String requestUri = operation.getValue().path("requestUri").asText("");
            if (method.isEmpty() || !requestUri.startsWith("/")) {
                throw new IllegalStateException(RESOURCE_NAME + " gives s3 " + operation.getKey()
                        + " no HTTP method or no request URI");
            }
            if (!requestUri.startsWith(BUCKET_ROUTE)) {
                return;
            }
            for (String parameter : requestUri.substring(BUCKET_ROUTE.length()).split("&")) {
                if (!parameter.isEmpty() && parameter.indexOf('=') < 0) {
                    found.computeIfAbsent(parameter, ignored -> new TreeMap<>())
                            .computeIfAbsent(method, ignored -> new TreeSet<>())
                            .add(operation.getKey());
                }
            }
        });
        if (found.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " gives S3 no bucket sub-resource");
        }
        Map<String, Map<String, List<String>>> operations = new TreeMap<>();
        found.forEach((name, byMethod) -> {
            Map<String, List<String>> methods = new TreeMap<>();
            byMethod.forEach((method, names) -> methods.put(method, List.copyOf(names)));
            operations.put(name, Map.copyOf(methods));
        });
        return new S3BucketSubresources(Map.copyOf(operations), List.copyOf(found.keySet()));
    }
}

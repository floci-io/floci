package io.floci.aws.services.iam;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.floci.aws.core.common.VendoredResources;

import java.io.IOException;
import java.io.InputStream;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * The IAM action AWS checks for an operation whose action is not the operation's own name, read once
 * from the vendored {@code aws/iam-authorized-actions.json}.
 *
 * <p>A request that names its operation, in a Query {@code Action} or an {@code X-Amz-Target}
 * header, is authorized as {@code <namespace>:<Operation>}. For most operations that is the action
 * AWS checks, but not for all: SQS {@code SendMessageBatch} is
 * authorized as {@code sqs:SendMessage} and SNS {@code PublishBatch} as {@code sns:Publish}, and
 * neither batch name is an IAM action at all. Authorized as its own name, such a call is denied
 * under a least-privilege policy AWS honours, and granted by a policy naming something AWS does not
 * check.
 *
 * <p>The file is generated by {@code tools/aws/regen_iam_authorized_actions.py} from the
 * {@code Operations} AWS's Service Reference publishes per service, which name the actions each SDK
 * operation is authorized by. It carries only operations authorized by exactly one action of their
 * own namespace under another name, counting neither a Billing console permission nor a
 * tag-on-create permission beside that action: Budgets {@code CreateBudget} is authorized as
 * {@code budgets:ModifyBudget} and {@code DescribeBudgets} as {@code budgets:ViewBudget}. The generator
 * documents the shapes it leaves out and why.
 * {@code make iam-authorized-actions-check} gates its shape offline and
 * {@code make iam-authorized-actions-verify} checks every entry against AWS. A namespace Floci
 * authorizes under a name other than the IAM namespace matches nothing here, and its operations keep
 * their own names.
 *
 * <p>The file also lists, for each credential scope whose REST routes {@code aws/rest-routes.json} reads, the
 * actions the Service Reference gives no resource type ({@link #actsOnNoResourceType}): AWS authorizes them on
 * {@code *}, which is what Floci checks a REST request on until it reads the resources in its path. And it lists
 * the operations of those scopes a request on whose route is checked as the action its HTTP method names
 * ({@link #actionFor(String, String, String)}): API Gateway's management API is authorized as
 * {@code apigateway:GET}, {@code apigateway:POST} and so on, and {@code TagResource} is a PUT in v1 and a POST in v2.
 *
 * <p>A missing or malformed resource is a build defect, not a runtime condition, so loading fails
 * with {@link IllegalStateException} rather than degrading to an empty map, which would silently put
 * every operation back on its own name.
 */
public final class IamAuthorizedActions {

    static final String RESOURCE_NAME = "aws/iam-authorized-actions.json";

    /**
     * Operations kept on their own name because another check recognizes them by it. AWS authorizes
     * DynamoDB {@code TransactGetItems} as {@code dynamodb:GetItem}, and Floci does too, item by
     * item: the transaction check in {@code IamConditionContextResolver} picks the call out by its own
     * name and checks every {@code Get} as {@code dynamodb:GetItem} on its own table, with its own
     * {@code dynamodb:LeadingKeys}. Renamed here, the call would skip that check and be authorized as
     * a single {@code GetItem} whose body has no top-level {@code Key}, so no
     * {@code dynamodb:LeadingKeys}, which a {@code ForAllValues} condition accepts: a fine-grained
     * policy would grant every key.
     */
    private static final Set<String> KEPT_FOR_ITEM_CHECKS = Set.of("dynamodb:TransactGetItems");

    private static final ObjectMapper MAPPER = new ObjectMapper();

    /**
     * The file: the action of each operation it names, keyed by {@code <namespace>:<Operation>}, the actions of
     * no resource type, as {@code <namespace>:<Action>} in lower case, and the operations authorized by method, as
     * {@code <namespace>:<Operation>}.
     */
    record Table(Map<String, String> actions, Set<String> withoutResourceTypes, Set<String> byMethod) {
    }

    private static final class Holder {
        static final Table TABLE = VendoredResources.read(RESOURCE_NAME, "IAM authorized action map",
                IamAuthorizedActions::parse);
    }

    private IamAuthorizedActions() {
    }

    /**
     * The action AWS checks for {@code operation} under {@code namespace}: the one the vendored file
     * names for it, or else the operation's own name.
     */
    public static String actionFor(String namespace, String operation) {
        String own = namespace + ":" + operation;
        if (KEPT_FOR_ITEM_CHECKS.contains(own)) {
            return own;
        }
        return Holder.TABLE.actions().getOrDefault(own, own);
    }

    /**
     * The action AWS checks for a request of {@code method} on a route of {@code operation} under {@code namespace}:
     * the one that method names, {@code <namespace>:<METHOD>}, for an operation the file lists as authorized by
     * method, or else {@link #actionFor(String, String)}'s.
     */
    public static String actionFor(String namespace, String operation, String method) {
        return Holder.TABLE.byMethod().contains(namespace + ":" + operation)
                ? namespace + ":" + method.toUpperCase(Locale.ROOT)
                : actionFor(namespace, operation);
    }

    /**
     * Whether AWS authorizes {@code action}, as {@code <namespace>:<Action>}, on no resource type: one the file lists
     * for a credential scope whose REST routes are read, matched without regard to case, as IAM matches action
     * names. An action of any other scope is not known here, so is not one.
     */
    public static boolean actsOnNoResourceType(String action) {
        return action != null && Holder.TABLE.withoutResourceTypes().contains(action.toLowerCase(Locale.ROOT));
    }

    /** The file's entries. */
    static Table parse(InputStream in) throws IOException {
        JsonNode document = MAPPER.readTree(in);
        JsonNode namespaces = document.path("authorizedActions");
        if (!namespaces.isObject() || namespaces.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no authorizedActions");
        }
        Map<String, String> actions = new LinkedHashMap<>();
        namespaces.properties().forEach(namespace -> {
            if (!namespace.getValue().isObject()) {
                throw new IllegalStateException(RESOURCE_NAME + " has authorizedActions."
                        + namespace.getKey() + " as something other than a map");
            }
            namespace.getValue().properties().forEach(operation -> {
                String action = operation.getValue().asText("");
                if (!action.startsWith(namespace.getKey() + ":")
                        || action.length() == namespace.getKey().length() + 1) {
                    throw new IllegalStateException(RESOURCE_NAME + " maps " + namespace.getKey() + ":"
                            + operation.getKey() + " to " + operation.getValue()
                            + ", which is not an action of " + namespace.getKey());
                }
                actions.put(namespace.getKey() + ":" + operation.getKey(), action);
            });
        });
        return new Table(Map.copyOf(actions), withoutResourceTypes(document.path("actionsWithoutResourceTypes")),
                byMethod(document.path("authorizedByMethod")));
    }

    /** The operations authorized by method, each scope's a list of operation names. */
    private static Set<String> byMethod(JsonNode scopes) {
        if (!scopes.isObject()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no authorizedByMethod");
        }
        Set<String> operations = new HashSet<>();
        scopes.properties().forEach(scope -> {
            if (!scope.getValue().isArray()) {
                throw new IllegalStateException(RESOURCE_NAME + " has authorizedByMethod."
                        + scope.getKey() + " as something other than a list");
            }
            scope.getValue().forEach(operation -> {
                if (!operation.isTextual() || operation.textValue().isBlank()) {
                    throw new IllegalStateException(RESOURCE_NAME + " lists " + operation + " among "
                            + scope.getKey() + "'s operations authorized by method");
                }
                operations.add(scope.getKey() + ":" + operation.textValue());
            });
        });
        return Set.copyOf(operations);
    }

    /** The actions of no resource type, each scope's a list of action names. */
    private static Set<String> withoutResourceTypes(JsonNode scopes) {
        if (!scopes.isObject()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no actionsWithoutResourceTypes");
        }
        Set<String> actions = new HashSet<>();
        scopes.properties().forEach(scope -> {
            if (!scope.getValue().isArray()) {
                throw new IllegalStateException(RESOURCE_NAME + " has actionsWithoutResourceTypes."
                        + scope.getKey() + " as something other than a list");
            }
            scope.getValue().forEach(action -> {
                if (!action.isTextual() || action.textValue().isBlank()) {
                    throw new IllegalStateException(RESOURCE_NAME + " lists " + action + " among "
                            + scope.getKey() + "'s actions without resource types");
                }
                actions.add((scope.getKey() + ":" + action.textValue()).toLowerCase(Locale.ROOT));
            });
        });
        return Set.copyOf(actions);
    }
}

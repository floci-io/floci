/**
 * The routes of the REST operations botocore models, read once from the vendored {@code aws/rest-routes.json}:
 * the operation a REST request is, from its method, its path and the query its route requires, for a request
 * {@link IamActionRegistry}'s rules give no action.
 *
 * <p>A route is its operation's {@code requestUri}: literal segments, a {@code {label}} taking one segment, and a
 * greedy {@code {label+}} taking the rest of the path, and a query it names ({@code ?tagging},
 * {@code ?list-type=2}) must be on the request, with that value when it gives one. A request is matched on its path
 * as the router matched it, still percent-encoded and without a trailing {@code /}, so an encoded {@code /} stays
 * inside its label. A segment may end in a matrix parameter ({@code ;name=value}), which the router ignores: the
 * path it routed carries none, and one read from the request URI still matches. Of the routes a request matches, it
 * is the most specific one's operation: compared segment by segment from the left, a literal before a segment mixing
 * a literal and a label, before a label, before a greedy label, then the route naming more of the query.
 *
 * <p>A request a route filter moved under an internal prefix ({@code SignedServiceRoute}) is matched on its path
 * without the prefix, which is the path the model gives its operation. The router matched it decoded, so a label's
 * value holds the slashes its encoding hid (a key ARN on the Payment Cryptography data plane), and the controller's
 * route takes them: a path that matches no route with each label taking one segment is matched again with each
 * label taking as many as its value spans. So is a request whose controller takes a label's value with the slashes
 * it was sent with unencoded (a durable execution's ARN, an EKS access entry's principal), the route whose labels
 * the path then gives the values the router gave the path parameters of the method it dispatched to being its own.
 *
 * <p>An operation may have alternative routes, the bare paths a shared controller also serves it on, with where
 * the request carries the members the path no longer holds, and the alternative's own method when it is not the
 * operation's: API Gateway v1 tags with a PUT, and the shared tags controller's bare path tags with a POST.
 *
 * <p>A model AWS documents on a page of its own rather than in botocore (its {@code documented} block, Glue's Iceberg
 * REST endpoint) routes another API's requests: Apache Iceberg's REST catalog, whose bodies carry none of the Glue
 * operation's members. A request one of its routes takes is {@link Match#documented}, so nothing reads a member from
 * it.
 *
 * <p>The file is generated by {@code tools/aws/regen_rest_routes.py}, which fails when one route names two
 * operations of a credential scope. A missing or malformed resource is a build defect, so loading fails with
 * {@link IllegalStateException} rather than leaving every route it holds unchecked.
 */
final class IamRestRoutes {

    static final String RESOURCE_NAME = "aws/rest-routes.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Pattern LABEL = Pattern.compile("\\{[^}]+}");
    private static final Pattern GREEDY = Pattern.compile("\\{[^}]+\\+}");
    private static final String MATRIX = "(?:;[^/]*)?";
    private static final Set<String> METHODS = Set.of("GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS");

    private static final int LITERAL = 3;
    private static final int MIXED = 2;
    private static final int ONE_SEGMENT = 1;
    private static final int REST_OF_PATH = 0;

    /**
     * A matched operation, decoded path labels, generated alternative member locations, whether the route is a
     * documented model's, whose request carries none of the operation's members, and the model whose route it is.
     */
    record Match(String operation, Map<String, String> labels, Map<String, String> located, boolean documented,
                 String model) {
    }

    /**
     * A route: its operation, its path as a pattern capturing each label in turn, the labels' names, each segment's
     * rank, the query it names, the members its alternative locates, whether its model is a documented one, the
     * query parameters and headers its operation's request must carry where several operations share the route
     * ({@code requires}), whether botocore marks the operation deprecated, and its model.
     */
    private record Route(String operation, Pattern path, Pattern spanning, List<String> labels, int[] ranks,
                         Map<String, String> query, Map<String, String> located, boolean documented,
                         Set<String> requiredQuery, Set<String> requiredHeaders, boolean deprecated, String model) {

        /** The route's pattern: each label taking one segment, or, spanning, the segments its value spans. */
        Pattern pattern(boolean spanned) {
            return spanned ? spanning : path;
        }

        boolean matches(String requestPath, MultivaluedMap<String, String> parameters, boolean spanned) {
            if (!pattern(spanned).matcher(requestPath).matches()) {
                return false;
            }
            for (Map.Entry<String, String> parameter : query.entrySet()) {
                String value = parameters == null ? null : parameters.getFirst(parameter.getKey());
                if (value == null || !parameter.getValue().isEmpty() && !parameter.getValue().equals(value)) {
                    return false;
                }
            }
            return requiredQuery.stream().allMatch(parameter -> parameters != null && parameters.containsKey(parameter));
        }

        /**
         * Whether the request carries every header the route's operation requires; with no headers known, a route
         * requiring one cannot be told to match.
         */
        boolean carries(MultivaluedMap<String, String> headers) {
            return requiredHeaders.isEmpty() || headers != null && requiredHeaders.stream()
                    .allMatch(header -> headers.keySet().stream().anyMatch(header::equalsIgnoreCase));
        }

        /** The value the path gives each label, decoded as the router decodes a path parameter. */
        Map<String, String> labelValues(String requestPath, boolean spanned) {
            Matcher matcher = pattern(spanned).matcher(requestPath);
            if (!matcher.matches()) {
                return Map.of();
            }
            Map<String, String> values = new LinkedHashMap<>();
            for (int i = 0; i < labels.size(); i++) {
                values.put(labels.get(i), URLDecoder.decode(matcher.group(i + 1).replace("+", "%2B"),
                        StandardCharsets.UTF_8));
            }
            return Map.copyOf(values);
        }

        /**
         * Whether this route is more specific than the other, as {@link IamRestRoutes} orders them: by its segments, the
         * query it names, then by what its operation's request must carry, a route requiring all the other requires and
         * more outranking it, and a current operation before a deprecated one requiring the same. The generator lets a
         * route's operations through only when what any two require together is what one of them requires, so of the
         * routes a request matches one requires all the others do (UploadPartCopy, over CopyObject and UploadPart).
         */
        boolean outranks(Route other) {
            int compared = Arrays.compare(ranks, other.ranks);
            if (compared != 0) {
                return compared > 0;
            }
            if (query.size() != other.query.size()) {
                return query.size() > other.query.size();
            }
            Set<String> needs = needs();
            Set<String> otherNeeds = other.needs();
            if (!needs.equals(otherNeeds)) {
                return needs.containsAll(otherNeeds) || !otherNeeds.containsAll(needs) && needs.size() > otherNeeds.size();
            }
            return !deprecated && other.deprecated;
        }

        /** What the route's operation's request must carry: its query parameters, then its headers. */
        private Set<String> needs() {
            Set<String> needs = new HashSet<>();
            requiredQuery.forEach(parameter -> needs.add("?" + parameter));
            requiredHeaders.forEach(header -> needs.add(header.toLowerCase(Locale.ROOT) + ":"));
            return needs;
        }
    }

    private static final class Holder {
        static final IamRestRoutes VENDORED = VendoredResources.read(RESOURCE_NAME, "REST route table",
                IamRestRoutes::parse);
    }

    /** Each credential scope's routes, by method. */
    private final Map<String, Map<String, List<Route>>> routes;
    private final Map<String, Integer> accessDeniedStatuses;
    /** The credential scopes a documented model routes. */
    private final Set<String> documentedScopes;
    /** Each botocore model's API version, by model. */
    private final Map<String, String> apiVersions;
    /** Each botocore model's credential scope, the signing name AWS signs its requests with, by model. */
    private final Map<String, String> modelScopes;

    private IamRestRoutes(Map<String, Map<String, List<Route>>> routes, Map<String, Integer> accessDeniedStatuses,
                          Set<String> documentedScopes, Map<String, String> apiVersions,
                          Map<String, String> modelScopes) {
        this.routes = routes;
        this.accessDeniedStatuses = accessDeniedStatuses;
        this.documentedScopes = documentedScopes;
        this.apiVersions = apiVersions;
        this.modelScopes = modelScopes;
    }

    /**
     * The scope a request of {@code scope} is matched under: the scope itself when the file routes it, and else, for
     * the name of a botocore model the file vendors, the scope its model gives, the signing name AWS signs that
     * model's requests with. AppConfig Data's model, {@code appconfigdata}, is signed {@code appconfig}, so a request
     * Floci serves under the model's name is matched to that model's routes, as one an SDK signs is.
     */
    String signedScope(String scope) {
        return scope == null || routes.containsKey(scope) ? scope : modelScopes.getOrDefault(scope, scope);
    }

    /** The API version of the botocore model of that name, null for a model the file does not give one. */
    String apiVersion(String model) {
        return model == null ? null : apiVersions.get(model);
    }

    /** The vendored routes. */
    static IamRestRoutes vendored() {
        return Holder.VENDORED;
    }

    /**
     * The operation whose route a request of the credential scope matches, the most specific one's when it
     * matches several; empty when it matches none, or its scope is one the file does not route.
     */
    Optional<String> operation(String scope, String method, String path, MultivaluedMap<String, String> query) {
        return match(scope, method, path, query).map(Match::operation);
    }

    /**
     * As {@link #operation}, for a path a route filter moved under an internal prefix, given without it: when it
     * matches no route, its labels may span the slashes their decoded values hold.
     */
    Optional<String> operation(String scope, String method, String path, MultivaluedMap<String, String> query,
                               boolean movedUnderPrefix) {
        return match(scope, method, path, query, movedUnderPrefix).map(Match::operation);
    }

    /** As {@link #operation}, with the values the request's path gives the route's labels. */
    Optional<Match> match(String scope, String method, String path, MultivaluedMap<String, String> query) {
        return match(scope, method, path, query, false);
    }

    /** As {@link #operation(String, String, String, MultivaluedMap, boolean)}, with the label values. */
    Optional<Match> match(String scope, String method, String path, MultivaluedMap<String, String> query,
                          boolean movedUnderPrefix) {
        return match(scope, method, path, query, movedUnderPrefix, null);
    }

    /**
     * As {@link #match(String, String, String, MultivaluedMap, boolean)}, the headers a route's operation requires
     * checked against the request's {@code headers}.
     */
    Optional<Match> match(String scope, String method, String path, MultivaluedMap<String, String> query,
                          boolean movedUnderPrefix, MultivaluedMap<String, String> headers) {
        return match(scope, method, path, query, movedUnderPrefix, headers, List.of());
    }

    /**
     * As {@link #match(String, String, String, MultivaluedMap, boolean, MultivaluedMap)}, for a request the router
     * dispatched giving the path parameters of the method serving it the values {@code routed}: of the routes the
     * request matches, one whose labels the path gives those values is the route of the operation the router chose,
     * so it is the match when there is one. EKS takes a principal whose IAM path holds an {@code access-policies}
     * segment as an access entry, whose DeleteAccessEntry route the DisassociateAccessPolicy one would outrank. A
     * request that matches no route with each label taking one segment is the route whose labels, each taking as
     * many segments as it spans, the path gives those values, when one does: its controller took a value's slashes
     * unencoded.
     */
    Optional<Match> match(String scope, String method, String path, MultivaluedMap<String, String> query,
                          boolean movedUnderPrefix, MultivaluedMap<String, String> headers, Collection<String> routed) {
        String requestPath = IamActionRegistry.withoutTrailingSlash(path);
        Optional<Match> match = best(scope, method, requestPath, query, false, headers, routed, false);
        return match.isPresent() ? match : best(scope, method, requestPath, query, true, headers, routed,
                !movedUnderPrefix);
    }

    private Optional<Match> best(String scope, String method, String requestPath, MultivaluedMap<String, String> query,
                                 boolean spanned, MultivaluedMap<String, String> headers, Collection<String> routed,
                                 boolean routedOnly) {
        Route best = ranked(scope, method, requestPath, query, spanned, headers, routed, routedOnly).best();
        return best == null ? Optional.empty()
                : Optional.of(new Match(best.operation(), best.labelValues(requestPath, spanned), best.located(),
                        best.documented(), best.model()));
    }

    /**
     * Whether the request is taken alike by the routes of two operations, none outranking the other: a request naming
     * two of S3's sub-resources ({@code PUT /bucket?cors&policy}) matches both their routes, and no botocore client
     * sends one, so which it is depends on the handler alone.
     */
    boolean ambiguous(String scope, String method, String path, MultivaluedMap<String, String> query,
                      boolean movedUnderPrefix, MultivaluedMap<String, String> headers) {
        return ambiguous(scope, method, path, query, movedUnderPrefix, headers, List.of());
    }

    /**
     * As {@link #ambiguous(String, String, String, MultivaluedMap, boolean, MultivaluedMap)}, of the routes whose labels
     * the router gave the values {@code routed}, when the request matches one.
     */
    boolean ambiguous(String scope, String method, String path, MultivaluedMap<String, String> query,
                      boolean movedUnderPrefix, MultivaluedMap<String, String> headers, Collection<String> routed) {
        String requestPath = IamActionRegistry.withoutTrailingSlash(path);
        Ranked ranked = ranked(scope, method, requestPath, query, false, headers, routed, false);
        return ranked.best() == null
                ? ranked(scope, method, requestPath, query, true, headers, routed, !movedUnderPrefix).tied()
                : ranked.tied();
    }

    /** The route a request matches that outranks the others it matches, and whether another operation's ties it. */
    private record Ranked(Route best, boolean tied) {
    }

    /**
     * The routes a request matches, ranked: those whose labels the path gives the values {@code routed} when any does,
     * and only those when {@code routedOnly}.
     */
    private Ranked ranked(String scope, String method, String requestPath, MultivaluedMap<String, String> query,
                          boolean spanned, MultivaluedMap<String, String> headers, Collection<String> routed,
                          boolean routedOnly) {
        List<Route> matching = new ArrayList<>();
        for (Route route : routes.getOrDefault(scope, Map.of()).getOrDefault(method, List.of())) {
            if (route.matches(requestPath, query, spanned) && route.carries(headers)) {
                matching.add(route);
            }
        }
        List<String> routedValues = routed.stream().sorted().toList();
        List<Route> agreeing = routedValues.isEmpty() ? List.of() : matching.stream()
                .filter(route -> route.labelValues(requestPath, spanned).values().stream().sorted().toList()
                        .equals(routedValues))
                .toList();
        if (!agreeing.isEmpty() || routedOnly) {
            matching = agreeing;
        }
        Route best = null;
        for (Route route : matching) {
            if (best == null || route.outranks(best)) {
                best = route;
            }
        }
        Route winner = best;
        boolean tied = winner != null && matching.stream().anyMatch(route -> route != winner
                && !winner.outranks(route) && !winner.operation().equals(route.operation()));
        return new Ranked(best, tied);
    }

    /** The modelled denial status, or the existing protocol default when the model declares none. */
    int accessDeniedStatus(String scope, int fallback) {
        return scope == null ? fallback : accessDeniedStatuses.getOrDefault(scope, fallback);
    }

    /** Whether the file routes any request of the credential scope. */
    boolean routes(String scope) {
        return routes.containsKey(scope);
    }

    /** Whether a documented model routes requests of the credential scope. */
    boolean documents(String scope) {
        return documentedScopes.contains(scope);
    }

    /**
     * Whether a route of the credential scope, of any method, takes the path and query: the path is one of its
     * model's, whatever method a request sends to it.
     */
    boolean takesPath(String scope, String path, MultivaluedMap<String, String> query) {
        return routes.getOrDefault(scope, Map.of()).keySet().stream()
                .anyMatch(method -> match(scope, method, path, query).isPresent());
    }

    static IamRestRoutes parse(InputStream in) throws IOException {
        JsonNode document = MAPPER.readTree(in);
        JsonNode models = document == null ? null : document.path("models");
        if (models == null || !models.isObject() || models.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no models");
        }
        Map<String, Map<String, List<Route>>> routes = new HashMap<>();
        Map<String, Integer> denialStatuses = new HashMap<>();
        Set<String> documentedScopes = new HashSet<>();
        Map<String, String> apiVersions = new HashMap<>();
        Map<String, String> modelScopes = new HashMap<>();
        models.properties().forEach(model -> {
            String scope = model.getValue().path("credentialScope").asText("");
            if (!scope.isEmpty()) {
                modelScopes.put(model.getKey(), scope);
            }
            if (model.getValue().path("apiVersion").isTextual()) {
                apiVersions.put(model.getKey(), model.getValue().path("apiVersion").asText());
            }
            JsonNode operations = model.getValue().path("operations");
            if (scope.isEmpty() || !operations.isObject() || operations.isEmpty()) {
                throw new IllegalStateException(RESOURCE_NAME + " gives model " + model.getKey()
                        + " no credential scope or no operations");
            }
            if (model.getValue().has("accessDeniedStatus")) {
                JsonNode status = model.getValue().get("accessDeniedStatus");
                if (!status.isIntegralNumber() || !status.canConvertToInt() || status.asInt() < 400 || status.asInt() > 599) {
                    throw new IllegalStateException(RESOURCE_NAME + " gives model " + model.getKey()
                            + " an invalid access-denied HTTP status");
                }
                Integer previous = denialStatuses.putIfAbsent(scope, status.asInt());
                if (previous != null && previous.intValue() != status.asInt()) {
                    throw new IllegalStateException(RESOURCE_NAME + " gives scope " + scope
                            + " conflicting access-denied HTTP statuses");
                }
            }
            JsonNode documentation = model.getValue().path("documented");
            if (!documentation.isMissingNode() && !documentation.isObject()) {
                throw new IllegalStateException(RESOURCE_NAME + " gives model " + model.getKey()
                        + " an invalid documented block");
            }
            boolean documented = documentation.isObject();
            if (documented) {
                documentedScopes.add(scope);
            }
            operations.properties().forEach(operation -> {
                String method = operation.getValue().path("method").asText("");
                String requestUri = operation.getValue().path("requestUri").asText("");
                if (!METHODS.contains(method) || !requestUri.startsWith("/")) {
                    throw new IllegalStateException(RESOURCE_NAME + " gives " + model.getKey() + " "
                            + operation.getKey() + " no HTTP method or no request URI");
                }
                JsonNode requires = operation.getValue().path("requires");
                routes.computeIfAbsent(scope, ignored -> new HashMap<>())
                        .computeIfAbsent(method, ignored -> new ArrayList<>())
                        .add(route(operation.getKey(), requestUri, Map.of(), documented, names(requires.path("query")),
                                names(requires.path("headers")),
                                operation.getValue().path("deprecated").asBoolean(false), model.getKey()));
                JsonNode alternatives = operation.getValue().path("alternatives");
                if (!alternatives.isMissingNode() && !alternatives.isArray()) {
                    throw new IllegalStateException(RESOURCE_NAME + " gives " + operation.getKey()
                            + " invalid alternative routes");
                }
                alternatives.forEach(alternative -> {
                    String uri = alternative.path("requestUri").asText("");
                    String alternativeMethod = alternative.has("method") ? alternative.get("method").asText("") : method;
                    JsonNode members = alternative.path("located");
                    if (!uri.startsWith("/") || !members.isObject() || !METHODS.contains(alternativeMethod)) {
                        throw new IllegalStateException(RESOURCE_NAME + " gives " + operation.getKey()
                                + " an invalid alternative route");
                    }
                    Map<String, String> located = new HashMap<>();
                    members.properties().forEach(member -> {
                        String source = member.getValue().asText("");
                        if (!member.getValue().isTextual() || member.getKey().isEmpty()
                                || !("body".equals(source) || source.startsWith("?") && source.length() > 1)) {
                            throw new IllegalStateException(RESOURCE_NAME + " gives " + operation.getKey()
                                    + " an invalid alternative member location");
                        }
                        located.put(member.getKey(), source);
                    });
                    routes.get(scope).computeIfAbsent(alternativeMethod, ignored -> new ArrayList<>())
                            .add(route(operation.getKey(), uri, Map.copyOf(located), documented, Set.of(), Set.of(),
                                    false, model.getKey()));
                });
            });
        });
        Map<String, Map<String, List<Route>>> copied = new HashMap<>();
        routes.forEach((scope, byMethod) -> {
            Map<String, List<Route>> methods = new HashMap<>();
            byMethod.forEach((method, list) -> methods.put(method, List.copyOf(list)));
            copied.put(scope, Map.copyOf(methods));
        });
        return new IamRestRoutes(Map.copyOf(copied), Map.copyOf(denialStatuses), Set.copyOf(documentedScopes),
                Map.copyOf(apiVersions), Map.copyOf(modelScopes));
    }

    /** The strings of a JSON array, none when it is missing. */
    private static Set<String> names(JsonNode array) {
        Set<String> found = new HashSet<>();
        array.forEach(name -> found.add(name.asText()));
        return Set.copyOf(found);
    }

    /** A route of the operation from its request URI, its path's segments and the query after its {@code ?}. */
    private static Route route(String operation, String requestUri, Map<String, String> located, boolean documented,
                               Set<String> requiredQuery, Set<String> requiredHeaders, boolean deprecated,
                               String model) {
        int question = requestUri.indexOf('?');
        String path = IamActionRegistry.withoutTrailingSlash(question < 0 ? requestUri : requestUri.substring(0, question));
        List<String> segments = path.equals("/") ? List.of() : List.of(path.substring(1).split("/", -1));
        StringBuilder pattern = new StringBuilder();
        StringBuilder spanning = new StringBuilder();
        List<String> labels = new ArrayList<>();
        int[] ranks = new int[segments.size()];
        for (int i = 0; i < segments.size(); i++) {
            String segment = segments.get(i);
            pattern.append('/');
            spanning.append('/');
            if (GREEDY.matcher(segment).matches()) {
                pattern.append("(.+)");
                spanning.append("(.+)");
                labels.add(segment.substring(1, segment.length() - 2));
                ranks[i] = REST_OF_PATH;
                continue;
            }
            Matcher label = LABEL.matcher(segment);
            int literalFrom = 0;
            boolean labelled = false;
            while (label.find()) {
                pattern.append(Pattern.quote(segment.substring(literalFrom, label.start()))).append("([^/]+)");
                spanning.append(Pattern.quote(segment.substring(literalFrom, label.start()))).append("(.+)");
                labels.add(segment.substring(label.start() + 1, label.end() - 1));
                literalFrom = label.end();
                labelled = true;
            }
            pattern.append(Pattern.quote(segment.substring(literalFrom))).append(MATRIX);
            spanning.append(Pattern.quote(segment.substring(literalFrom))).append(MATRIX);
            ranks[i] = !labelled ? LITERAL : LABEL.matcher(segment).matches() ? ONE_SEGMENT : MIXED;
        }
        Map<String, String> query = new LinkedHashMap<>();
        if (question >= 0) {
            for (String parameter : requestUri.substring(question + 1).split("&")) {
                int equals = parameter.indexOf('=');
                query.put(equals < 0 ? parameter : parameter.substring(0, equals),
                        equals < 0 ? "" : parameter.substring(equals + 1));
            }
        }
        return new Route(operation, Pattern.compile(pattern.isEmpty() ? "/" : pattern.toString()),
                Pattern.compile(spanning.isEmpty() ? "/" : spanning.toString()), List.copyOf(labels), ranks,
                Map.copyOf(query), located, documented, requiredQuery, requiredHeaders, deprecated, model);
    }
}

package io.github.hectorvent.floci.core.common;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.ws.rs.container.ContainerRequestContext;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The Lambda network connectors a request passes, which the caller also needs
 * {@code lambda:PassNetworkConnector} on. The Lambda developer guide: "The caller must have
 * {@code lambda:PassNetworkConnector} on the referenced connector whenever a {@code create-web-function} or
 * {@code create-web-function-revision} call sets {@code egressNetworkConnectorArn}."
 *
 * <p>Where each operation's request names them is read once from the vendored
 * {@code aws/iam-passed-network-connectors.json}, generated by
 * {@code tools/aws/regen_iam_passed_network_connectors.py} from AWS's Service Reference and botocore's models.
 * A member the request leaves out or gives as an empty list passes the Lambda-managed connector the file names
 * for it, as AWS checks a MicroVM's default connectors.
 *
 * <p>A missing or malformed resource is a build defect, so loading fails with
 * {@link IllegalStateException} rather than leaving every operation it reads unchecked.
 */
final class PassedNetworkConnectors {

    static final String RESOURCE_NAME = "aws/iam-passed-network-connectors.json";
    static final String ACTION = "lambda:PassNetworkConnector";

    private static final ObjectMapper MAPPER = new ObjectMapper();

    /** A member of a request that names connectors, and the Lambda-managed connector it passes when it names none. */
    record Member(String path, List<PassedRoleMembers.Step> steps, String whenAbsent) {
    }

    private static final class Holder {
        static final Map<String, List<Member>> TABLE = VendoredResources.read(RESOURCE_NAME,
                "IAM passed network connector table", PassedNetworkConnectors::parse);
    }

    private PassedNetworkConnectors() {
    }

    /** The connectors a request for {@code operation} passes, in the order AWS checks them; empty when it passes none. */
    static List<String> of(String operation, ContainerRequestContext ctx, String region) {
        List<Member> members = Holder.TABLE.get(operation);
        if (members == null) {
            return List.of();
        }
        JsonNode body = PassedRoles.jsonBody(ctx);
        List<String> connectors = new ArrayList<>();
        for (Member member : members) {
            List<String> named = new ArrayList<>();
            PassedRoles.collect(body, member.steps(), 0, named);
            if (named.isEmpty() && member.whenAbsent() != null) {
                named.add(AwsArnUtils.Arn.of("lambda", region, "aws", "network-connector:" + member.whenAbsent())
                        .toString());
            }
            connectors.addAll(named);
        }
        return connectors;
    }

    static Map<String, List<Member>> table() {
        return Holder.TABLE;
    }

    static Map<String, List<Member>> parse(InputStream in) throws IOException {
        JsonNode operations = MAPPER.readTree(in).path("operations");
        if (!operations.isObject() || operations.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no operations");
        }
        Map<String, List<Member>> table = new LinkedHashMap<>();
        operations.properties().forEach(operation -> {
            JsonNode entry = operation.getValue();
            if (entry.has("notRead")) {
                return;
            }
            if (!entry.path("connectors").isArray() || entry.path("connectors").isEmpty()) {
                throw new IllegalStateException(RESOURCE_NAME + " says nothing usable for " + operation.getKey());
            }
            List<Member> members = new ArrayList<>();
            for (JsonNode connector : entry.path("connectors")) {
                String path = connector.path("member").asText("");
                List<PassedRoleMembers.Step> steps = PassedRoleMembers.steps(path);
                if (steps == null) {
                    throw new IllegalStateException(RESOURCE_NAME + " reads " + operation.getKey() + " at " + path
                            + ", which is no member path");
                }
                members.add(new Member(path, steps, connector.hasNonNull("whenAbsent")
                        ? connector.get("whenAbsent").asText() : null));
            }
            table.put(operation.getKey(), List.copyOf(members));
        });
        return Map.copyOf(table);
    }
}

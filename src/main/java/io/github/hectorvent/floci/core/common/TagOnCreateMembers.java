package io.github.hectorvent.floci.core.common;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * Which tagging action each operation that tags what it creates needs, and where its request carries the
 * tags, read once from the vendored {@code aws/iam-tag-on-create.json}.
 *
 * <p>The file is generated by {@code tools/aws/regen_iam_tag_on_create.py} from AWS's Service Reference,
 * which lists the tagging action among an operation's authorized actions, and from botocore's model of the
 * request, which gives the members that carry the tags. Every operation of the namespaces it reads is in it
 * once: with the members to read, as one Floci checks by hand, or as one whose request carries no tags it
 * can read. {@code make iam-tag-on-create-check} re-derives every member from botocore and
 * {@code make iam-tag-on-create-verify} checks every operation against AWS.
 *
 * <p>A missing or malformed resource is a build defect, so loading fails with
 * {@link IllegalStateException} rather than leaving every operation it reads unchecked.
 */
final class TagOnCreateMembers {

    static final String RESOURCE_NAME = "aws/iam-tag-on-create.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();

    /**
     * A member of a request that carries tags: a list of tag structures, whose key and value members are
     * named {@code key} and {@code value}, or a map, for which both are null. {@code steps} lead to it in a
     * JSON or CBOR body, the last one into the list or the map. {@code queryTags} matches the form parameters
     * the Query protocol sends a tag's key or value as, read along {@code querySteps}: its {@code tag} group
     * names the tag and its {@code field} group which of the two; null for a member a form cannot carry.
     */
    record Member(String path, List<PassedRoleMembers.Step> steps, List<PassedRoleMembers.Step> querySteps,
                  String key, String value, Pattern queryTags) {
    }

    /**
     * What an operation needs: one tagging action, whether it takes the CreateAction key, whether the
     * operation's own action takes the request's tags as well, and its members.
     */
    record Entry(String tagging, boolean createAction, boolean requestTags, List<Member> members) {
    }

    /** The file: the entries read from it, and the operations checked by hand or not read. */
    record Table(Map<String, Entry> entries, Set<String> byHand, Set<String> notRead,
                 Set<String> namespaces, Set<String> notCovered, Set<String> otherNamespaces) {
    }

    private static final class Holder {
        static final Table TABLE = VendoredResources.read(RESOURCE_NAME, "IAM tag-on-create table",
                TagOnCreateMembers::parse);
    }

    private TagOnCreateMembers() {
    }

    /** What a request for {@code operation}, as {@code <namespace>:<Operation>}, needs; null when this table does not read it. */
    static Entry of(String operation) {
        return Holder.TABLE.entries().get(operation);
    }

    static Table table() {
        return Holder.TABLE;
    }

    static Table parse(InputStream in) throws IOException {
        JsonNode document = MAPPER.readTree(in);
        JsonNode operations = document.path("operations");
        if (!operations.isObject() || operations.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no operations");
        }
        Map<String, Entry> entries = new LinkedHashMap<>();
        Set<String> byHand = new LinkedHashSet<>();
        Set<String> notRead = new LinkedHashSet<>();
        operations.properties().forEach(operation -> {
            JsonNode entry = operation.getValue();
            if (entry.has("byHand")) {
                byHand.add(operation.getKey());
            } else if (entry.has("notRead")) {
                notRead.add(operation.getKey());
            } else if (entry.path("tags").isArray() && !entry.path("tags").isEmpty()
                    && entry.path("tagging").isArray() && entry.path("tagging").size() == 1) {
                List<Member> members = new ArrayList<>();
                for (JsonNode member : entry.path("tags")) {
                    members.add(member(operation.getKey(), member));
                }
                entries.put(operation.getKey(), new Entry(entry.path("tagging").get(0).asText(),
                        entry.path("createAction").asBoolean(false), entry.path("requestTags").asBoolean(false),
                        List.copyOf(members)));
            } else {
                throw new IllegalStateException(RESOURCE_NAME + " says nothing usable for " + operation.getKey());
            }
        });
        return new Table(Map.copyOf(entries), Set.copyOf(byHand), Set.copyOf(notRead),
                Set.copyOf(document.path("namespaces").propertyStream().map(Map.Entry::getKey).toList()),
                Set.copyOf(document.path("notCovered").propertyStream().map(Map.Entry::getKey).toList()),
                Set.copyOf(document.path("otherNamespaces").valueStream().map(JsonNode::asText).toList()));
    }

    private static Member member(String operation, JsonNode member) {
        String path = member.path("member").asText("");
        List<PassedRoleMembers.Step> steps = PassedRoleMembers.steps(path);
        String key = member.hasNonNull("key") ? member.get("key").asText() : null;
        String value = member.hasNonNull("value") ? member.get("value").asText() : null;
        PassedRoleMembers.Into last = steps == null ? null : steps.getLast().into();
        if (last != PassedRoleMembers.Into.LIST && last != PassedRoleMembers.Into.MAP
                || (last == PassedRoleMembers.Into.LIST) != (key != null && value != null)) {
            throw new IllegalStateException(RESOURCE_NAME + " reads " + operation + " at " + path
                    + ", which is no path to a tag list or map");
        }
        List<PassedRoleMembers.Step> querySteps = member.hasNonNull("query")
                ? PassedRoleMembers.steps(member.get("query").asText()) : steps;
        if (querySteps == null || querySteps.getLast().into() != last) {
            throw new IllegalStateException(RESOURCE_NAME + " reads " + operation + "'s tags at " + path
                    + " from a form by no path to a tag list or map");
        }
        return new Member(path, steps, querySteps, key, value,
                queryTags(querySteps, key, value, operation.startsWith("ec2:")));
    }

    /**
     * The form parameters the Query protocol sends a tag's key or value as. Lists are numbered under their
     * name, generically as {@code member.N}, under the name their shape gives elements or bare, as
     * {@link AwsQueryLists} reads them, each tag then carrying its {@code key} and {@code value} members.
     * A map's entries are numbered under its name, as {@code entry.N} or bare when flattened, each with a
     * {@code key} and a {@code value} in either case. A step into a map before the tags is not read from a
     * form. EC2's tag specifications are read under either spelling, {@code TagSpecification} or
     * {@code TagSpecifications}, since {@code Ec2QueryHandler} applies the tags of either to every action.
     */
    private static Pattern queryTags(List<PassedRoleMembers.Step> steps, String key, String value, boolean ec2) {
        StringBuilder regex = new StringBuilder("(?<tag>");
        for (int i = 0; i < steps.size(); i++) {
            PassedRoleMembers.Step step = steps.get(i);
            boolean last = i == steps.size() - 1;
            if (step.into() == PassedRoleMembers.Into.KEY || !last && step.into() == PassedRoleMembers.Into.MAP) {
                return null;
            }
            if (i > 0) {
                regex.append("\\.");
            }
            boolean specifications = ec2 && i == 0
                    && ("TagSpecification".equals(step.name()) || "TagSpecifications".equals(step.name()));
            regex.append(specifications ? "TagSpecifications?" : Pattern.quote(step.name()));
            if (step.into() == PassedRoleMembers.Into.LIST) {
                regex.append(step.key().isEmpty() ? "(?:\\.member)?" : "(?:\\.member|\\." + Pattern.quote(step.key()) + ")?")
                        .append("\\.\\d+");
            } else if (step.into() == PassedRoleMembers.Into.MAP) {
                regex.append("(?:\\.entry)?\\.\\d+");
            }
        }
        regex.append(")\\.(?<field>");
        if (key == null) {
            regex.append("(?i:key|value)");
        } else {
            regex.append(Pattern.quote(key)).append('|').append(Pattern.quote(value));
        }
        return Pattern.compile(regex.append(')').toString());
    }
}

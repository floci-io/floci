package io.github.hectorvent.floci.core.common;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The resources each operation's request names, for the namespaces whose ARNs {@code ResourceArnBuilder} does not
 * build itself, read once from the vendored {@code aws/iam-request-resources.json}.
 *
 * <p>The file is generated by {@code tools/aws/regen_iam_request_resources.py} from AWS's Service Reference, which
 * lists the resource types each action acts on and each type's ARN formats, and from botocore's model of the
 * request, which gives the members that name them. {@code make iam-request-resources-check} re-derives every
 * operation from botocore and {@code make iam-request-resources-verify} checks them against AWS.
 *
 * <p>A missing or malformed resource is a build defect, so loading fails with {@link IllegalStateException}
 * rather than leaving every operation it reads checked on {@code *}.
 */
final class RequestResourceMembers {

    static final String RESOURCE_NAME = "aws/iam-request-resources.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Pattern VARIABLE = Pattern.compile("\\$\\{(\\w+)}");
    private static final Pattern MEMBER = Pattern.compile("[A-Za-z][A-Za-z0-9_]*(\\[])?");
    /** An ARN format's leading resource type word, and the rest of its resource. */
    private static final Pattern RESOURCE_PART = Pattern.compile(
            "^arn:\\$\\{Partition}:[^:]*:[^:]*:[^:]*:([A-Za-z][A-Za-z0-9-]*)(.*)$");
    /** The one id a child type's format appends to its parent's. */
    private static final Pattern APPENDED_ID = Pattern.compile("[/:]\\$\\{\\w+}");

    /** A top-level request member that holds a string, or a list of them when {@code list}. */
    record Member(String name, boolean list) {
    }

    /**
     * A resource type's ARN format, with {@code ${Partition}}, {@code ${Region}}, {@code ${Account}} and the
     * variables a request fills, and the pattern an ARN of the type matches; {@code unqualified} when its service
     * checks an ARN of it given with a qualifier, one more {@code :<name>} past the format, without that qualifier
     * (Step Functions checks a version or an alias on its state machine's ARN).
     */
    record ArnFormat(String format, Pattern pattern, boolean unqualified) {

        /** The ARN as its service checks it: an unqualified type's without the qualifier it may carry. */
        String checked(String arn) {
            if (!unqualified) {
                return arn;
            }
            long colons = format.chars().filter(c -> c == ':').count();
            int at = -1;
            for (long found = 0; found <= colons; found++) {
                at = arn.indexOf(':', at + 1);
                if (at < 0) {
                    return arn;
                }
            }
            return arn.substring(0, at);
        }
    }

    /**
     * A resource a request names: by a member holding its ARN, which names a resource of one of {@code types} when
     * it matches the type's format, or by members filling the variables of one type's format, the others open,
     * only {@code when} each member named has one of its values, an empty one for the member absent, in the
     * account an {@code account} member gives (ECR's {@code registryId}), or else the request's. An ARN member's
     * value is read up to the character {@code before}, when there is one, as its handler drops the rest.
     */
    record Resource(List<String> types, Member arn, Map<String, Member> fill, Map<String, List<String>> when,
                    Member account, String before) {
    }

    /**
     * A resource a create makes under a parent its action acts on, from a member holding the parent's ARN: the
     * parent's resource with its leading type word {@code parentWord} replaced by {@code childWord} and an open
     * id appended after {@code separator} ({@code listener/app/<lb>/<id>/*} under {@code loadbalancer/app/...}).
     */
    record Created(String type, String parent, Member arn, String parentWord, String childWord, String separator) {
    }

    /**
     * The file: each operation's resources and the resources it creates under a parent, as
     * {@code <namespace>:<Operation>}, each namespace's ARN formats, and the namespaces it reads, those built by
     * hand, those not read yet, and the others with resource types.
     */
    record Table(Map<String, List<Resource>> operations, Map<String, List<Created>> creates,
                 Map<String, Map<String, ArnFormat>> formats, Set<String> namespaces, Set<String> handBuilt,
                 Set<String> notCovered, Set<String> otherNamespaces) {
    }

    private static final class Holder {
        static final Table TABLE = VendoredResources.read(RESOURCE_NAME, "IAM request resources table",
                RequestResourceMembers::parse);
    }

    private RequestResourceMembers() {
    }

    static Table table() {
        return Holder.TABLE;
    }

    static Table parse(InputStream in) throws IOException {
        JsonNode document = MAPPER.readTree(in);
        JsonNode operations = document.path("operations");
        if (!operations.isObject() || operations.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no operations");
        }
        Set<String> namespaces = Set.copyOf(document.path("namespaces").propertyStream().map(Map.Entry::getKey).toList());
        Map<String, Map<String, ArnFormat>> formats = new LinkedHashMap<>();
        document.path("arnFormats").properties().forEach(namespace -> {
            Set<String> unqualified = names(document.path("unqualified").path(namespace.getKey()));
            Map<String, ArnFormat> types = new LinkedHashMap<>();
            namespace.getValue().properties().forEach(type -> {
                String format = type.getValue().asText("");
                if (!format.startsWith("arn:${Partition}:")) {
                    throw new IllegalStateException(RESOURCE_NAME + " gives " + namespace.getKey() + "'s "
                            + type.getKey() + " no ARN format");
                }
                types.put(type.getKey(), new ArnFormat(format, pattern(format), unqualified.contains(type.getKey())));
            });
            formats.put(namespace.getKey(), Map.copyOf(types));
        });
        document.path("unqualified").properties().forEach(namespace -> {
            Set<String> types = formats.getOrDefault(namespace.getKey(), Map.of()).keySet();
            if (!namespace.getValue().isArray() || !types.containsAll(names(namespace.getValue()))) {
                throw new IllegalStateException(RESOURCE_NAME + " checks " + namespace.getKey() + "'s "
                        + namespace.getValue() + " without a qualifier, no types with an ARN format");
            }
        });
        Map<String, List<Resource>> entries = new LinkedHashMap<>();
        Map<String, List<Created>> creates = new LinkedHashMap<>();
        operations.properties().forEach(operation -> {
            String namespace = operation.getKey().substring(0, Math.max(0, operation.getKey().indexOf(':')));
            if (!namespaces.contains(namespace)) {
                throw new IllegalStateException(RESOURCE_NAME + " reads " + operation.getKey()
                        + ", of no namespace it reads");
            }
            List<Resource> resources = new ArrayList<>();
            for (JsonNode resource : operation.getValue().path("resources")) {
                resources.add(resource(operation.getKey(), resource, formats.getOrDefault(namespace, Map.of())));
            }
            entries.put(operation.getKey(), List.copyOf(resources));
            List<Created> made = new ArrayList<>();
            for (JsonNode created : operation.getValue().path("creates")) {
                made.add(created(operation.getKey(), created, formats.getOrDefault(namespace, Map.of())));
            }
            if (!made.isEmpty()) {
                creates.put(operation.getKey(), List.copyOf(made));
            }
        });
        return new Table(Map.copyOf(entries), Map.copyOf(creates), Map.copyOf(formats), namespaces,
                names(document.path("handBuilt")),
                Set.copyOf(document.path("notCovered").propertyStream().map(Map.Entry::getKey).toList()),
                names(document.path("otherNamespaces")));
    }

    private static Set<String> names(JsonNode list) {
        return Set.copyOf(list.valueStream().map(JsonNode::asText).toList());
    }

    private static Resource resource(String operation, JsonNode resource, Map<String, ArnFormat> formats) {
        if (resource.has("arn")) {
            List<String> types = resource.path("types").valueStream().map(JsonNode::asText).toList();
            if (types.isEmpty() || !formats.keySet().containsAll(types)) {
                throw new IllegalStateException(RESOURCE_NAME + " reads an ARN for " + operation
                        + " of types with no format: " + types);
            }
            String before = resource.has("before") ? resource.path("before").asText("") : null;
            if (before != null && before.length() != 1) {
                throw new IllegalStateException(RESOURCE_NAME + " reads an ARN for " + operation
                        + " before " + before + ", no one character");
            }
            return new Resource(types, member(operation, resource.path("arn").asText("")), Map.of(), Map.of(), null,
                    before);
        }
        String type = resource.path("type").asText("");
        ArnFormat format = formats.get(type);
        if (format == null || !resource.path("fill").isObject()) {
            throw new IllegalStateException(RESOURCE_NAME + " names a " + type + " for " + operation
                    + ", a type with no format or no variables to fill");
        }
        Set<String> variables = Set.copyOf(VARIABLE.matcher(format.format()).results().map(m -> m.group(1)).toList());
        Map<String, Member> fill = new LinkedHashMap<>();
        resource.path("fill").properties().forEach(variable -> {
            if (!variables.contains(variable.getKey())) {
                throw new IllegalStateException(RESOURCE_NAME + " fills " + variable.getKey() + " for " + operation
                        + ", no variable of " + type + "'s format");
            }
            fill.put(variable.getKey(), member(operation, variable.getValue().asText("")));
        });
        if (fill.values().stream().filter(Member::list).count() > 1) {
            throw new IllegalStateException(RESOURCE_NAME + " fills " + type + " for " + operation
                    + " from more than one list");
        }
        Map<String, List<String>> when = new LinkedHashMap<>();
        resource.path("when").properties().forEach(member -> {
            if (member(operation, member.getKey()).list() || !member.getValue().isArray() || member.getValue().isEmpty()) {
                throw new IllegalStateException(RESOURCE_NAME + " names a " + type + " for " + operation
                        + " when " + member.getKey() + " has no values");
            }
            when.put(member.getKey(), member.getValue().valueStream().map(value -> value.isNull() ? "" : value.asText())
                    .toList());
        });
        Member account = resource.has("account") ? member(operation, resource.path("account").asText("")) : null;
        if (account != null && (account.list() || !format.format().contains("${Account}"))) {
            throw new IllegalStateException(RESOURCE_NAME + " takes " + type + "'s account for " + operation
                    + " from " + account.name() + ", no member of one account or a type of none");
        }
        return new Resource(List.of(type), null, Map.copyOf(fill), Map.copyOf(when), account, null);
    }

    private static Created created(String operation, JsonNode created, Map<String, ArnFormat> formats) {
        String type = created.path("type").asText("");
        String parent = created.path("parent").asText("");
        Matcher child = formats.containsKey(type) ? RESOURCE_PART.matcher(formats.get(type).format()) : null;
        Matcher under = formats.containsKey(parent) ? RESOURCE_PART.matcher(formats.get(parent).format()) : null;
        if (child == null || under == null || !child.matches() || !under.matches()
                || child.group(1).equals(under.group(1)) || !child.group(2).startsWith(under.group(2))
                || !APPENDED_ID.matcher(child.group(2).substring(under.group(2).length())).matches()) {
            throw new IllegalStateException(RESOURCE_NAME + " creates a " + type + " for " + operation
                    + " under a " + parent + ", no parent of it");
        }
        String separator = child.group(2).substring(under.group(2).length(), under.group(2).length() + 1);
        return new Created(type, parent, member(operation, created.path("arn").asText("")), under.group(1),
                child.group(1), separator);
    }

    private static Member member(String operation, String path) {
        if (!MEMBER.matcher(path).matches()) {
            throw new IllegalStateException(RESOURCE_NAME + " reads " + operation + " at " + path + ", which is no member");
        }
        return path.endsWith("[]") ? new Member(path.substring(0, path.length() - 2), true) : new Member(path, false);
    }

    /**
     * What an ARN of the format matches: its literal parts, a partition, any Region and account, and anything for
     * each other variable but nothing.
     */
    static Pattern pattern(String format) {
        StringBuilder regex = new StringBuilder("^");
        Matcher variable = VARIABLE.matcher(format);
        int at = 0;
        while (variable.find()) {
            regex.append(Pattern.quote(format.substring(at, variable.start())));
            regex.append(switch (variable.group(1)) {
                case "Partition" -> "[^:]+";
                case "Region", "Account" -> "[^:]*";
                default -> ".+";
            });
            at = variable.end();
        }
        return Pattern.compile(regex.append(Pattern.quote(format.substring(at))).append('$').toString());
    }
}

package io.github.hectorvent.floci.services.iam;

import io.github.hectorvent.floci.services.iam.model.DelegationPermission;
import io.github.hectorvent.floci.services.iam.model.DelegationRequest;
import io.github.hectorvent.floci.services.iam.model.PolicyParameter;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;

/**
 * Renders a delegation request as the summary {@code GetHumanReadableSummary} answers.
 *
 * <p>AWS generates that text with a large language model, which an emulator cannot reproduce and
 * should not imitate, so this is the one part of the family that is deliberately not AWS's own
 * answer. The format is sourced: the reference's example answers "Human readable summary in
 * Markdown format", and the console describes the section it backs as "a high-level overview
 * generated by AI that can help you understand what categories of AWS services can be accessed
 * and what types of actions can be performed in each service". So the text is Markdown, and it
 * says what a customer deciding on the request needs: what is being asked for, by whom, for how
 * long, and where the request has got to.
 *
 * <p>Every line is read off the record rather than inferred, which is what makes the same request
 * summarize the same way twice. The services-and-actions half of the console's description is the
 * one thing missing: AWS resolves a request's {@code PermissionPolicy} from a policy template
 * registered out of band, no API registers one, and nothing here renders a policy, so there is no
 * document to read a service list out of. The template and the parameters the request asks with
 * are named instead, which is what Floci knows about it.
 */
final class DelegationRequestSummary {

    /** A Markdown block marker, where one opens a block: at the start of a line. */
    private static final Pattern BLOCK_MARKER =
            Pattern.compile("^(\\s*)([#>*+=~|-]|\\d+[.)])");

    private static final Pattern WHITESPACE = Pattern.compile("\\s+");

    private DelegationRequestSummary() {
    }

    /**
     * The request as Markdown, at most {@code maxLength} characters.
     *
     * <p>A record that is missing a member leaves its line out rather than printing an empty one:
     * most of the shape is optional, and a summary is read by a person.
     */
    static String markdown(DelegationRequest request, int maxLength) {
        List<String> lines = new ArrayList<>();
        lines.add("# Delegation request " + request.getDelegationRequestId());
        addParagraph(lines, paragraph(request.getDescription()));
        addParagraph(lines,
                prefixed("A note from the requester: ", paragraph(request.getRequestMessage())));

        lines.add("");
        lines.add("## What is being asked for");
        lines.add("");
        lines.add("- Filed by " + requestor(request));
        addBullet(lines, prefixed("Workflow ", code(request.getRequestorWorkflowId())));
        addBullet(lines, session(request));
        DelegationPermission permissions = request.getPermissions();
        if (permissions != null) {
            addBullet(lines, prefixed("Policy template ", code(permissions.getPolicyTemplateArn())));
            for (PolicyParameter parameter : permissions.getParameters()) {
                addBullet(lines, parameter(parameter));
            }
        }
        for (String boundary : request.getRolePermissionRestrictionArns()) {
            addBullet(lines, "A role it creates is bounded by " + code(boundary));
        }
        if (Boolean.TRUE.equals(request.getOnlySendByOwner())) {
            lines.add("- Only the identity that claimed the request may release the exchange token");
        }

        lines.add("");
        lines.add("## Where the request stands");
        lines.add("");
        addBullet(lines, state(request));
        addBullet(lines, prefixed("Claimed by ", code(request.getOwnerId())));
        addBullet(lines, prefixed("Approved by ", code(request.getApproverId())));
        addBullet(lines, prefixed("Filed ", instant(request.getCreateDate())));
        addBullet(lines, prefixed("Expires ", instant(request.getExpirationTime())));
        addBullet(lines, prefixed("Notes for the approver: ", inline(request.getNotes())));
        addBullet(lines, prefixed("Rejected because: ", inline(request.getRejectionReason())));
        return capped(String.join("\n", lines) + "\n", maxLength);
    }

    /** Who asked, by account, with the registered partner name when onboarding assigned one. */
    private static String requestor(DelegationRequest request) {
        String account = request.getRequestorId() == null
                ? "an account the record does not name" : "account " + request.getRequestorId();
        String name = inline(request.getRequestorName());
        return name == null ? account : name + ", " + account;
    }

    /**
     * The window the credentials run for. The delegation period starts at the release rather than
     * at the exchange, which is the part of the shape a reader is most likely to get wrong.
     */
    private static String session(DelegationRequest request) {
        if (request.getSessionDuration() == null) {
            return null;
        }
        return "A session of " + length(request.getSessionDuration())
                + ", counted from the moment the exchange token is released";
    }

    /** Whole hours and whole minutes read as themselves; anything else stays in seconds. */
    private static String length(int seconds) {
        if (seconds % 3600 == 0) {
            return plural(seconds / 3600, "hour");
        }
        if (seconds % 60 == 0) {
            return plural(seconds / 60, "minute");
        }
        return plural(seconds, "second");
    }

    private static String plural(int count, String unit) {
        return count + " " + unit + (count == 1 ? "" : "s");
    }

    private static String parameter(PolicyParameter parameter) {
        if (parameter.getName() == null) {
            return null;
        }
        StringBuilder line = new StringBuilder("Parameter ").append(code(parameter.getName()));
        if (parameter.getType() != null) {
            line.append(" (").append(parameter.getType()).append(')');
        }
        List<String> values = new ArrayList<>();
        for (String value : parameter.getValues()) {
            // A value the record carries without one, which an indexed member can arrive as,
            // has nothing to render: the line reads without it rather than printing "null".
            String rendered = code(value);
            if (rendered != null) {
                values.add(rendered);
            }
        }
        if (!values.isEmpty()) {
            line.append(": ").append(String.join(", ", values));
        }
        return line.toString();
    }

    private static String state(DelegationRequest request) {
        if (request.getState() == null) {
            return null;
        }
        String updated = instant(request.getUpdatedTime());
        return "State " + code(request.getState().name())
                + (updated == null ? "" : ", last moved " + updated);
    }

    private static String instant(Instant instant) {
        return instant == null ? null : instant.toString();
    }

    /**
     * A value as inline code. A code span carries no newline and ends at the first run of
     * backticks as long as the one that opened it, so the value is flattened onto one line and
     * fenced with one backtick more than its own longest run, padded when it begins or ends with
     * one. Without that, a parameter value holding a backtick would close the span early and the
     * rest of the line would read as the summary's own prose.
     */
    private static String code(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }
        String text = WHITESPACE.matcher(value.strip()).replaceAll(" ");
        String fence = "`".repeat(longestBacktickRun(text) + 1);
        String padding = text.startsWith("`") || text.endsWith("`") ? " " : "";
        return fence + padding + text + padding + fence;
    }

    private static int longestBacktickRun(String text) {
        int longest = 0;
        int run = 0;
        for (int index = 0; index < text.length(); index++) {
            run = text.charAt(index) == '`' ? run + 1 : 0;
            longest = Math.max(longest, run);
        }
        return longest;
    }

    /**
     * Requester text as a paragraph that cannot become structure.
     *
     * <p>{@code delegationRequestDescriptionType} and {@code requestMessageType} both admit a
     * newline and every printable character, so a value opening a line with a Markdown marker
     * would otherwise forge a heading or a bullet inside a summary that is read as Floci's own
     * account of the request. The marker is escaped where it would be read, at the start of a
     * line, and a backtick anywhere, which would open a span.
     */
    private static String paragraph(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }
        List<String> escaped = new ArrayList<>();
        for (String line : value.strip().split("\n", -1)) {
            escaped.add(BLOCK_MARKER.matcher(line).replaceFirst("$1\\\\$2").replace("`", "\\`"));
        }
        return String.join("\n", escaped);
    }

    /**
     * The same text inside a bullet, where it is one line: a newline would break the list rather
     * than the line, so whitespace is collapsed, and only a backtick needs escaping mid-line.
     */
    private static String inline(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }
        return WHITESPACE.matcher(value.strip()).replaceAll(" ").replace("`", "\\`");
    }

    private static String prefixed(String prefix, String value) {
        return value == null || value.isBlank() ? null : prefix + value.strip();
    }

    private static void addBullet(List<String> lines, String text) {
        if (text != null) {
            lines.add("- " + text);
        }
    }

    private static void addParagraph(List<String> lines, String text) {
        if (text != null && !text.isBlank()) {
            lines.add("");
            lines.add(text.strip());
        }
    }

    /**
     * {@code summaryContentType} caps the content, so a request carrying long parameter values is
     * cut at the last whole line that fits rather than mid-sentence.
     */
    private static String capped(String content, int maxLength) {
        if (content.length() <= maxLength) {
            return content;
        }
        int lastBreak = content.lastIndexOf('\n', maxLength);
        return lastBreak < 0 ? content.substring(0, maxLength) : content.substring(0, lastBreak);
    }
}

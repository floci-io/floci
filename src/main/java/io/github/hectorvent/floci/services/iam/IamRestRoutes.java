package io.github.hectorvent.floci.services.iam;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.github.hectorvent.floci.core.common.VendoredResources;
import jakarta.ws.rs.core.MultivaluedMap;

import java.io.IOException;
import java.io.InputStream;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The routes of the REST operations botocore models, read once from the vendored {@code aws/rest-routes.json}:
 * the operation a REST request is, from its method, its path and the query its route requires, for a request
 * {@link IamActionRegistry}'s rules give no action.
 *
 * <p>A route is its operation's {@code requestUri}: literal segments, a {@code {label}} taking one segment, and a
 * greedy {@code {label+}} taking the rest of the path, and a query it names ({@code ?tagging},
 * {@code ?list-type=2}) must be on the request, with that value when it gives one. A request is matched on its path
 * as the router matched it, still percent-encoded and without a trailing {@code /}, so an encoded {@code /} stays
 * inside its label. A segment may end in a matrix parameter ({@code ;name=value}), which the router ignores: the
 * path it routed carries none, and one read from the request URI still matches. Of the routes a request matches, it
 * is the most specific one's operation: compared segment by segment from the left, a literal before a segment mixing
 * a literal and a label, before a label, before a greedy label, then the route naming more of the query.
 *
 * <p>The file is generated by {@code tools/aws/regen_rest_routes.py}, which fails when one route names two
 * operations of a credential scope read here. The scopes it lists as {@code handRouted} are not read: the
 * registry's rules authorize them alone. A missing or malformed resource is a build defect, so loading fails with
 * {@link IllegalStateException} rather than leaving every route it holds unchecked.
 */
final class IamRestRoutes {

    static final String RESOURCE_NAME = "aws/rest-routes.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Pattern LABEL = Pattern.compile("\\{[^}]+}");
    private static final Pattern GREEDY = Pattern.compile("\\{[^}]+\\+}");
    private static final String MATRIX = "(?:;[^/]*)?";
    private static final Set<String> METHODS = Set.of("GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS");

    private static final int LITERAL = 3;
    private static final int MIXED = 2;
    private static final int ONE_SEGMENT = 1;
    private static final int REST_OF_PATH = 0;

    /** A route a request matched: its operation, and the value its path gives each of the route's labels, decoded. */
    record Match(String operation, Map<String, String> labels) {
    }

    /**
     * A route: its operation, its path as a pattern capturing each label in turn, the labels' names, each segment's
     * rank, and the query it names.
     */
    private record Route(String operation, Pattern path, List<String> labels, int[] ranks, Map<String, String> query) {

        boolean matches(String requestPath, MultivaluedMap<String, String> parameters) {
            if (!path.matcher(requestPath).matches()) {
                return false;
            }
            for (Map.Entry<String, String> parameter : query.entrySet()) {
                String value = parameters == null ? null : parameters.getFirst(parameter.getKey());
                if (value == null || !parameter.getValue().isEmpty() && !parameter.getValue().equals(value)) {
                    return false;
                }
            }
            return true;
        }

        /** The value the path gives each label, decoded as the router decodes a path parameter. */
        Map<String, String> labelValues(String requestPath) {
            Matcher matcher = path.matcher(requestPath);
            if (!matcher.matches()) {
                return Map.of();
            }
            Map<String, String> values = new LinkedHashMap<>();
            for (int i = 0; i < labels.size(); i++) {
                values.put(labels.get(i), URLDecoder.decode(matcher.group(i + 1).replace("+", "%2B"),
                        StandardCharsets.UTF_8));
            }
            return Map.copyOf(values);
        }

        /** Whether this route is more specific than the other, as {@link IamRestRoutes} orders them. */
        boolean outranks(Route other) {
            int compared = Arrays.compare(ranks, other.ranks);
            return compared != 0 ? compared > 0 : query.size() > other.query.size();
        }
    }

    private static final class Holder {
        static final IamRestRoutes VENDORED = VendoredResources.read(RESOURCE_NAME, "REST route table",
                IamRestRoutes::parse);
    }

    /** Each credential scope's routes, by method. */
    private final Map<String, Map<String, List<Route>>> routes;

    private IamRestRoutes(Map<String, Map<String, List<Route>>> routes) {
        this.routes = routes;
    }

    /** The vendored routes. */
    static IamRestRoutes vendored() {
        return Holder.VENDORED;
    }

    /**
     * The operation whose route a request of the credential scope matches, the most specific one's when it
     * matches several; empty when it matches none, or its scope is one the file does not route.
     */
    Optional<String> operation(String scope, String method, String path, MultivaluedMap<String, String> query) {
        return match(scope, method, path, query).map(Match::operation);
    }

    /** As {@link #operation}, with the values the request's path gives the route's labels. */
    Optional<Match> match(String scope, String method, String path, MultivaluedMap<String, String> query) {
        String requestPath = IamActionRegistry.withoutTrailingSlash(path);
        Route best = null;
        for (Route route : routes.getOrDefault(scope, Map.of()).getOrDefault(method, List.of())) {
            if (route.matches(requestPath, query) && (best == null || route.outranks(best))) {
                best = route;
            }
        }
        return best == null ? Optional.empty() : Optional.of(new Match(best.operation(), best.labelValues(requestPath)));
    }

    /** Whether the file routes any request of the credential scope. */
    boolean routes(String scope) {
        return routes.containsKey(scope);
    }

    static IamRestRoutes parse(InputStream in) throws IOException {
        JsonNode document = MAPPER.readTree(in);
        JsonNode handRouted = document == null ? null : document.path("handRouted");
        JsonNode models = document == null ? null : document.path("models");
        if (handRouted == null || !handRouted.isObject() || !models.isObject() || models.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no handRouted scopes or no models");
        }
        Set<String> skipped = Set.copyOf(handRouted.propertyStream().map(Map.Entry::getKey).toList());
        Map<String, Map<String, List<Route>>> routes = new HashMap<>();
        models.properties().forEach(model -> {
            String scope = model.getValue().path("credentialScope").asText("");
            JsonNode operations = model.getValue().path("operations");
            if (scope.isEmpty() || !operations.isObject() || operations.isEmpty()) {
                throw new IllegalStateException(RESOURCE_NAME + " gives model " + model.getKey()
                        + " no credential scope or no operations");
            }
            if (skipped.contains(scope)) {
                return;
            }
            operations.properties().forEach(operation -> {
                String method = operation.getValue().path("method").asText("");
                String requestUri = operation.getValue().path("requestUri").asText("");
                if (!METHODS.contains(method) || !requestUri.startsWith("/")) {
                    throw new IllegalStateException(RESOURCE_NAME + " gives " + model.getKey() + " "
                            + operation.getKey() + " no HTTP method or no request URI");
                }
                routes.computeIfAbsent(scope, ignored -> new HashMap<>())
                        .computeIfAbsent(method, ignored -> new ArrayList<>())
                        .add(route(operation.getKey(), requestUri));
            });
        });
        Map<String, Map<String, List<Route>>> copied = new HashMap<>();
        routes.forEach((scope, byMethod) -> {
            Map<String, List<Route>> methods = new HashMap<>();
            byMethod.forEach((method, list) -> methods.put(method, List.copyOf(list)));
            copied.put(scope, Map.copyOf(methods));
        });
        return new IamRestRoutes(Map.copyOf(copied));
    }

    /** A route of the operation from its request URI, its path's segments and the query after its {@code ?}. */
    private static Route route(String operation, String requestUri) {
        int question = requestUri.indexOf('?');
        String path = IamActionRegistry.withoutTrailingSlash(question < 0 ? requestUri : requestUri.substring(0, question));
        List<String> segments = path.equals("/") ? List.of() : List.of(path.substring(1).split("/", -1));
        StringBuilder pattern = new StringBuilder();
        List<String> labels = new ArrayList<>();
        int[] ranks = new int[segments.size()];
        for (int i = 0; i < segments.size(); i++) {
            String segment = segments.get(i);
            pattern.append('/');
            if (GREEDY.matcher(segment).matches()) {
                pattern.append("(.+)");
                labels.add(segment.substring(1, segment.length() - 2));
                ranks[i] = REST_OF_PATH;
                continue;
            }
            Matcher label = LABEL.matcher(segment);
            int literalFrom = 0;
            boolean labelled = false;
            while (label.find()) {
                pattern.append(Pattern.quote(segment.substring(literalFrom, label.start()))).append("([^/]+)");
                labels.add(segment.substring(label.start() + 1, label.end() - 1));
                literalFrom = label.end();
                labelled = true;
            }
            pattern.append(Pattern.quote(segment.substring(literalFrom))).append(MATRIX);
            ranks[i] = !labelled ? LITERAL : LABEL.matcher(segment).matches() ? ONE_SEGMENT : MIXED;
        }
        Map<String, String> query = new LinkedHashMap<>();
        if (question >= 0) {
            for (String parameter : requestUri.substring(question + 1).split("&")) {
                int equals = parameter.indexOf('=');
                query.put(equals < 0 ? parameter : parameter.substring(0, equals),
                        equals < 0 ? "" : parameter.substring(equals + 1));
            }
        }
        return new Route(operation, Pattern.compile(pattern.isEmpty() ? "/" : pattern.toString()), List.copyOf(labels),
                ranks, Map.copyOf(query));
    }
}

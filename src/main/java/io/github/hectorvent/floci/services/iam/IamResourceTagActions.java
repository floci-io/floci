package io.github.hectorvent.floci.services.iam;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.github.hectorvent.floci.core.common.VendoredResources;

import java.io.IOException;
import java.io.InputStream;
import java.util.LinkedHashSet;
import java.util.Set;

/**
 * The actions whose target resource carries {@code aws:ResourceTag/<key>}, read once from the
 * vendored {@code aws/iam-resource-tag-actions.json}.
 *
 * <p>AWS publishes the resource types each action acts on and the condition keys each type
 * supports, and Floci resolves a type's tags only for the actions that name it. An action outside
 * this set has no {@code aws:ResourceTag} keys, so a policy conditioned on one denies it, as it
 * would on AWS for a resource whose type does not support tags. The batch operations are absent
 * because they are not IAM actions: SQS {@code SendMessageBatch} authorizes as
 * {@code sqs:SendMessage} and SNS {@code PublishBatch} as {@code sns:Publish}.
 *
 * <p>The file is generated by {@code tools/aws/regen_iam_resource_tag_actions.py} from the per
 * service Service Reference. {@code make iam-resource-tag-actions-check} gates its shape offline
 * and {@code make iam-resource-tag-actions-verify} checks every entry against AWS.
 *
 * <p>A missing or malformed resource is a build defect, not a runtime condition, so loading fails
 * with {@link IllegalStateException} rather than degrading to an empty set, which would leave every
 * action without its tags.
 */
public final class IamResourceTagActions {

    static final String RESOURCE_NAME = "aws/iam-resource-tag-actions.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final class Holder {
        static final Set<String> ACTIONS = VendoredResources.read(RESOURCE_NAME,
                "IAM resource-tag action list", IamResourceTagActions::parse);
    }

    private IamResourceTagActions() {
    }

    /** Whether AWS gives {@code action}'s resource the {@code aws:ResourceTag/<key>} keys. */
    public static boolean supports(String action) {
        return action != null && Holder.ACTIONS.contains(action);
    }

    static Set<String> parse(InputStream in) throws IOException {
        JsonNode namespaces = MAPPER.readTree(in).path("namespaces");
        if (!namespaces.isObject() || namespaces.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no namespaces");
        }
        Set<String> actions = new LinkedHashSet<>();
        namespaces.properties().forEach(namespace -> {
            if (!namespace.getValue().isArray()) {
                throw new IllegalStateException(RESOURCE_NAME + " has namespaces."
                        + namespace.getKey() + " as something other than a list");
            }
            String prefix = namespace.getKey() + ":";
            for (JsonNode action : namespace.getValue()) {
                if (!action.isTextual()) {
                    throw new IllegalStateException(RESOURCE_NAME + " has a non-string action under "
                            + namespace.getKey());
                }
                String name = action.asText();
                if (!name.startsWith(prefix) || name.length() == prefix.length()) {
                    throw new IllegalStateException(RESOURCE_NAME + " lists " + name + " under "
                            + namespace.getKey() + ", which is not its action");
                }
                actions.add(name);
            }
        });
        return Set.copyOf(actions);
    }
}
